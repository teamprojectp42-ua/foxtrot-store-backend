using Microsoft.Extensions.Options;
using SkiaSharp;

namespace foxtrot_store_backend.Services.LocalStorage;

public sealed class LocalStorageService : ILocalStorageService
{
    private const int BufferSize = 81920;

    private readonly string _rootPath;
    private readonly long _maxFileSizeBytes;
    private readonly long _maxImagePixels;
    private readonly ILogger<LocalStorageService> _logger;

    private static readonly Dictionary<string, AllowedImageType> AllowedTypes =
        new(StringComparer.OrdinalIgnoreCase)
        {
            ["image/jpeg"] = new(
                ".jpg",
                SKEncodedImageFormat.Jpeg,
                92),

            ["image/png"] = new(
                ".png",
                SKEncodedImageFormat.Png,
                100),

            ["image/webp"] = new(
                ".webp",
                SKEncodedImageFormat.Webp,
                90)
        };

    private static readonly HashSet<string> AllowedExtensions =
        new(StringComparer.OrdinalIgnoreCase)
        {
            ".jpg",
            ".png",
            ".webp"
        };

    public LocalStorageService(
        IOptions<LocalStorageOptions> options,
        IWebHostEnvironment environment,
        ILogger<LocalStorageService> logger)
    {
        ArgumentNullException.ThrowIfNull(options);
        ArgumentNullException.ThrowIfNull(environment);
        ArgumentNullException.ThrowIfNull(logger);

        var settings = options.Value;

        if (string.IsNullOrWhiteSpace(settings.RootPath))
        {
            throw new InvalidOperationException(
                "LocalStorage RootPath must be configured.");
        }

        if (settings.MaxFileSizeBytes <= 0)
        {
            throw new InvalidOperationException(
                "MaxFileSizeBytes must be greater than zero.");
        }

        if (settings.MaxImagePixels <= 0)
        {
            throw new InvalidOperationException(
                "MaxImagePixels must be greater than zero.");
        }

        _maxFileSizeBytes = settings.MaxFileSizeBytes;
        _maxImagePixels = settings.MaxImagePixels;
        _logger = logger;

        _rootPath = Path.GetFullPath(
            Path.IsPathRooted(settings.RootPath)
                ? settings.RootPath
                : Path.Combine(
                    environment.ContentRootPath,
                    settings.RootPath));

        Directory.CreateDirectory(_rootPath);
    }

    public async Task<string> SaveAsync(
        Stream fileStream,
        string contentType,
        CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(fileStream);
        cancellationToken.ThrowIfCancellationRequested();

        if (!fileStream.CanRead)
        {
            throw new ArgumentException(
                "The file stream must be readable.",
                nameof(fileStream));
        }

        if (string.IsNullOrWhiteSpace(contentType) ||
            !AllowedTypes.TryGetValue(contentType.Trim(), out var imageType))
        {
            throw new InvalidDataException(
                "Unsupported image type. Allowed types: JPEG, PNG and WEBP.");
        }

        var fileId = Guid.NewGuid().ToString("N");
        var fileKey = $"{fileId}{imageType.Extension}";

        // Temporary files are generated by the application,
        // never from a user-provided filename.
        var sourceTempPath = Path.Combine(
            _rootPath,
            $".{fileId}.upload");

        var normalizedTempPath = Path.Combine(
            _rootPath,
            $".{fileId}.normalized");

        var destinationPath = ResolveKey(fileKey);

        try
        {
            await CopyWithLimitAsync(
                fileStream,
                sourceTempPath,
                cancellationToken);

            cancellationToken.ThrowIfCancellationRequested();

            ValidateAndNormalizeImage(
                sourceTempPath,
                normalizedTempPath,
                imageType,
                cancellationToken);

            cancellationToken.ThrowIfCancellationRequested();

            // File.Move does not overwrite an existing destination.
            File.Move(normalizedTempPath, destinationPath);

            return fileKey;
        }
        finally
        {
            TryDeleteTemporaryFile(sourceTempPath);
            TryDeleteTemporaryFile(normalizedTempPath);
        }
    }

    public Task<Stream?> GetAsync(
        string filePath,
        CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();

        var fullPath = ResolveKey(filePath);

        if (!File.Exists(fullPath))
        {
            return Task.FromResult<Stream?>(null);
        }

        Stream stream = new FileStream(
            fullPath,
            FileMode.Open,
            FileAccess.Read,
            FileShare.Read,
            BufferSize,
            FileOptions.Asynchronous | FileOptions.SequentialScan);

        return Task.FromResult<Stream?>(stream);
    }

    public Task<bool> DeleteAsync(
        string filePath,
        CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();

        var fullPath = ResolveKey(filePath);

        if (!File.Exists(fullPath))
        {
            return Task.FromResult(false);
        }

        File.Delete(fullPath);

        return Task.FromResult(true);
    }

    private async Task CopyWithLimitAsync(
        Stream source,
        string destinationPath,
        CancellationToken cancellationToken)
    {
        await using var destination = new FileStream(
            destinationPath,
            FileMode.CreateNew,
            FileAccess.Write,
            FileShare.None,
            BufferSize,
            FileOptions.Asynchronous | FileOptions.SequentialScan);

        var buffer = new byte[BufferSize];
        long totalBytes = 0;

        while (true)
        {
            var bytesRead = await source.ReadAsync(
                buffer.AsMemory(),
                cancellationToken);

            if (bytesRead == 0)
            {
                break;
            }

            totalBytes += bytesRead;

            if (totalBytes > _maxFileSizeBytes)
            {
                throw new InvalidDataException(
                    $"The uploaded file exceeds the maximum size of " +
                    $"{_maxFileSizeBytes} bytes.");
            }

            await destination.WriteAsync(
                buffer.AsMemory(0, bytesRead),
                cancellationToken);
        }

        if (totalBytes == 0)
        {
            throw new InvalidDataException(
                "Empty files are not allowed.");
        }

        await destination.FlushAsync(cancellationToken);
    }

    private void ValidateAndNormalizeImage(
        string sourcePath,
        string normalizedPath,
        AllowedImageType expectedType,
        CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();

        using var codec = SKCodec.Create(
            sourcePath,
            out var codecResult);

        if (codec is null || codecResult != SKCodecResult.Success)
        {
            throw new InvalidDataException(
                "The uploaded file is not a valid supported image.");
        }

        if (codec.EncodedFormat != expectedType.Format)
        {
            throw new InvalidDataException(
                "The file content does not match its declared image type.");
        }

        // Only static images are allowed.
        if (codec.FrameCount != 1)
        {
            throw new InvalidDataException(
                "Animated images are not supported.");
        }

        // Check encoded dimensions before allocating the decoded bitmap.
        var imageInfo = codec.Info;

        if (imageInfo.Width <= 0 || imageInfo.Height <= 0)
        {
            throw new InvalidDataException(
                "The image has invalid dimensions.");
        }

        var encodedPixelCount =
            (long)imageInfo.Width * imageInfo.Height;

        if (encodedPixelCount > _maxImagePixels)
        {
            throw new InvalidDataException(
                $"The image exceeds the maximum of {_maxImagePixels} pixels.");
        }

        using var bitmap = SKBitmap.Decode(codec);

        if (bitmap is null ||
            bitmap.Width <= 0 ||
            bitmap.Height <= 0)
        {
            throw new InvalidDataException(
                "The image could not be decoded.");
        }

        // Check dimensions once more on the decoded bitmap.
        var decodedPixelCount = (long)bitmap.Width * bitmap.Height;

        if (decodedPixelCount > _maxImagePixels)
        {
            throw new InvalidDataException(
                $"The decoded image exceeds the maximum of {_maxImagePixels} pixels.");
        }

        cancellationToken.ThrowIfCancellationRequested();

        // Re-encoding strips the original metadata and any arbitrary trailing
        // content. The stored image is generated by the decoder/encoder.
        using var output = new FileStream(
            normalizedPath,
            FileMode.CreateNew,
            FileAccess.Write,
            FileShare.None,
            BufferSize,
            FileOptions.None);

        if (!bitmap.Encode(
                output,
                expectedType.Format,
                expectedType.Quality))
        {
            throw new InvalidDataException(
                "The image could not be normalized.");
        }

        output.Flush(flushToDisk: true);

        if (output.Length > _maxFileSizeBytes)
        {
            throw new InvalidDataException(
                "The normalized image exceeds the maximum file size.");
        }

        cancellationToken.ThrowIfCancellationRequested();
    }

    private string ResolveKey(string storageKey)
    {
        if (string.IsNullOrWhiteSpace(storageKey) ||
            Path.IsPathRooted(storageKey) ||
            storageKey.Contains('/') ||
            storageKey.Contains('\\'))
        {
            throw new ArgumentException(
                "Invalid storage file key.",
                nameof(storageKey));
        }

        var extension = Path.GetExtension(storageKey);
        var fileId = Path.GetFileNameWithoutExtension(storageKey);

        if (!AllowedExtensions.Contains(extension) ||
            !Guid.TryParseExact(fileId, "N", out _))
        {
            throw new ArgumentException(
                "Invalid storage file key.",
                nameof(storageKey));
        }

        var fullPath = Path.GetFullPath(
            Path.Combine(_rootPath, storageKey));

        var relativePath = Path.GetRelativePath(
            _rootPath,
            fullPath);

        if (relativePath == "." ||
            relativePath == ".." ||
            Path.IsPathRooted(relativePath) ||
            relativePath.StartsWith(
                $"..{Path.DirectorySeparatorChar}",
                StringComparison.Ordinal))
        {
            throw new ArgumentException(
                "The file path is outside the storage directory.",
                nameof(storageKey));
        }

        return fullPath;
    }

    private void TryDeleteTemporaryFile(string path)
    {
        try
        {
            File.Delete(path);
        }
        catch (Exception exception) when (
            exception is IOException or
            UnauthorizedAccessException or
            System.Security.SecurityException)
        {
            // Cleanup errors must not mask the original save/validation error.
            _logger.LogWarning(
                exception,
                "Failed to clean up a temporary local-storage file.");
        }
    }

    private sealed record AllowedImageType(
        string Extension,
        SKEncodedImageFormat Format,
        int Quality);
}